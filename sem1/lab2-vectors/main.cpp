// Сбрасывает ошибку ввода и выбрасывает остаток неправильно введенной строки
void clearInput() {
    cin.clear();
    cin.ignore(10000, '\n');
}

// Запрашивает целое число, пока пользователь не введет его правильно
int readInt(const string& prompt) {
    while (true) {
        cout << prompt;
        int value;
        if (cin >> value) {
            return value;
        }
        if (cin.eof()) {                // ввод закрыт (например, нажали Ctrl+Z)
            cout << endl << "Ввод завершен." << endl;
            exit(0);
        }
        cout << "Ошибка: нужно ввести целое число." << endl;
        clearInput();
    }
}

// Функция input (требуется в задании 2, используется в обоих заданиях):
// вводит целочисленный вектор с клавиатуры и возвращает его
vector<int> input() {
    int n = readInt("Введите количество элементов n: ");
    while (n < 0) {
        cout << "Ошибка: количество не может быть отрицательным." << endl;
        n = readInt("Введите количество элементов n: ");
    }

    vector<int> v(n);                   // вектор из n элементов
    if (n > 0) {
        cout << "Введите элементы вектора (" << n << " шт.) через пробел: ";
    }
    for (int i = 0; i < n; ++i) {
        while (!(cin >> v[i])) {        // повторяем, пока элемент не введен правильно
            if (cin.eof()) {
                cout << endl << "Ввод завершен." << endl;
                exit(0);
            }
            cout << "Ошибка: элемент номер " << (i + 1) << " не целое число. Введите его заново: ";
            clearInput();
        }
    }
    return v;
}

// Выводит вектор на экран, перебирая элементы с помощью итератора
void print(const vector<int>& v) {
    if (v.empty()) {
        cout << "(вектор пуст)" << endl;
        return;
    }
    for (vector<int>::const_iterator it = v.begin(); it != v.end(); ++it) {
        cout << *it << " ";             // *it это элемент, на который указывает итератор
    }
    cout << endl;
}

// ================================ Задание 1 ==================================
// 1. Запросить n и создать вектор из n целых чисел, вводимых с клавиатуры.
// 2. Удалить из вектора все элементы, которые являются полными квадратами
//    (например, 1, 4, 9, 16, ...).
// 3. Вывести полученный вектор.
// 4. Найти и вывести сумму элементов, оставшихся в векторе.

// Проверяет, является ли число полным квадратом (квадратом целого числа).
// Ноль тоже считается полным квадратом: 0 = 0 * 0.
bool isPerfectSquare(int x) {
    if (x < 0) {
        return false;                   // квадрат целого числа не бывает отрицательным
    }
    // берем корень, округляем до ближайшего целого и проверяем возведением в квадрат
    long long root = static_cast<long long>(sqrt(static_cast<double>(x)) + 0.5);
    return root * root == x;
}

void task1() {
    cout << endl << "=== Задание 1. Удаление полных квадратов ===" << endl;

    // 1. Ввод вектора
    vector<int> v = input();
    cout << "Исходный вектор: ";
    print(v);

    // 2. Удаление полных квадратов.
    // remove_if сдвигает в начало элементы, которые остаются, и возвращает итератор
    // на начало ненужного "хвоста", а erase отрезает этот хвост от вектора.
    v.erase(remove_if(v.begin(), v.end(), isPerfectSquare), v.end());

    // 3. Вывод полученного вектора
    cout << "Вектор без полных квадратов: ";
    print(v);

    // 4. Сумма оставшихся элементов
    long long sum = 0;                  // long long, чтобы сумма больших чисел не переполнилась
    for (vector<int>::const_iterator it = v.begin(); it != v.end(); ++it) {
        sum += *it;
    }
    cout << "Сумма оставшихся элементов: " << sum << endl;
}

// ================================ Задание 2 ==================================
// Написать функцию input, вводящую целочисленный вектор с клавиатуры.
// Определить количество троек элементов последовательности, в которых каждое
// число содержит цифру 3 в десятичной записи, а сумма элементов тройки является
// простым числом. В ответе записать два числа: количество найденных троек и
// минимальную сумму элементов таких троек.
// Тройка это три идущих подряд элемента последовательности.

// Проверяет, есть ли в десятичной записи числа цифра 3
bool containsDigit3(int x) {
    long long value = x;                // long long, чтобы модуль самого маленького int не переполнился
    if (value < 0) {
        value = -value;                 // знак на цифры не влияет
    }
    while (value > 0) {
        if (value % 10 == 3) {          // последняя цифра числа
            return true;
        }
        value /= 10;                    // отбрасываем последнюю цифру
    }
    return false;
}

// Проверяет, является ли число простым (делится только на 1 и на само себя)
bool isPrime(long long x) {
    if (x < 2) {
        return false;                   // 0, 1 и отрицательные числа простыми не являются
    }
    for (long long d = 2; d * d <= x; ++d) {    // делители достаточно проверять до корня из x
        if (x % d == 0) {
            return false;
        }
    }
    return true;
}

void task2() {
    cout << endl << "=== Задание 2. Тройки с цифрой 3 и простой суммой ===" << endl;

    vector<int> v = input();
    cout << "Последовательность: ";
    print(v);

    int count = 0;                      // количество подходящих троек
    long long minSum = 0;               // минимальная сумма среди подходящих троек
    bool found = false;                 // нашлась ли хотя бы одна тройка

    // i это индекс первого элемента тройки; у последней тройки он равен size - 3
    for (size_t i = 0; i + 2 < v.size(); ++i) {
        int a = v[i];
        int b = v[i + 1];
        int c = v[i + 2];
        if (containsDigit3(a) && containsDigit3(b) && containsDigit3(c)) {
            long long sum = static_cast<long long>(a) + b + c;
            if (isPrime(sum)) {
                cout << "  подходит тройка: " << a << " " << b << " " << c
                     << " (сумма " << sum << ")" << endl;
                ++count;
                if (!found || sum < minSum) {
                    minSum = sum;
                    found = true;
                }
            }
        }
    }

    cout << "Количество троек: " << count << endl;
    if (found) {
        cout << "Минимальная сумма: " << minSum << endl;
        cout << "Ответ: " << count << " " << minSum << endl;
    }
    else {
        cout << "Подходящих троек нет, поэтому минимальной суммы нет." << endl;
    }
}

